# Central host-independent environment. Source from bash/sh scripts:
#   . "$(dirname "$0")/env.sh"
# All external artifacts, build state, sockets, and logs live under
# ESHINE_WORK (default <repo>/.work). No $HOME or fixed /tmp paths.

REPO=$(cd "$(dirname "$0")/.." && pwd)
ESHINE_WORK=${ESHINE_WORK:-$REPO/.work}

# Legacy variable names remain accepted as overrides.
ESHINE_LINUX_DIR=${ESHINE_LINUX_DIR:-${LINUX_DIR:-$ESHINE_WORK/linux}}
ESHINE_MUSL_DIR=${ESHINE_MUSL_DIR:-${MUSL_BUILD_DIR:-$ESHINE_WORK/musl-build}}
ESHINE_CJSON_DIR=${ESHINE_CJSON_DIR:-${CJSON_BUILD_DIR:-$ESHINE_WORK/cjson-build}}
ESHINE_ZLIB_DIR=${ESHINE_ZLIB_DIR:-${ZLIB_BUILD_DIR:-$ESHINE_WORK/zlib-build}}
ESHINE_BUSYBOX_DIR=${ESHINE_BUSYBOX_DIR:-${BUSYBOX_BUILD_DIR:-$ESHINE_WORK/busybox-build}}
ESHINE_POKY_DIR=${ESHINE_POKY_DIR:-$ESHINE_WORK/poky}
ESHINE_YOCTO_BUILD=${ESHINE_YOCTO_BUILD:-$ESHINE_WORK/yocto-build}
ESHINE_RUN_DIR=${ESHINE_RUN_DIR:-$ESHINE_WORK/run}
ESHINE_LOG_DIR=${ESHINE_LOG_DIR:-$ESHINE_WORK/logs}
ESHINE_TMP_DIR=${ESHINE_TMP_DIR:-$ESHINE_WORK/tmp}
ESHINE_DOWNLOAD_DIR=${ESHINE_DOWNLOAD_DIR:-$ESHINE_WORK/cache/downloads}

ESHINE_LINUX_IMAGE=${ESHINE_LINUX_IMAGE:-$ESHINE_LINUX_DIR/linux-6.6/arch/arm64/boot/Image}
ESHINE_INITRAMFS=${ESHINE_INITRAMFS:-$ESHINE_LINUX_DIR/initramfs.cpio}
ESHINE_BUSYBOX=${ESHINE_BUSYBOX:-$REPO/tools/ramfs/bin/busybox}

CROSS=${CROSS:-aarch64-linux-gnu-}
ESHINE_QEMU=${ESHINE_QEMU:-qemu-system-aarch64}
ESHINE_GDB=${ESHINE_GDB:-gdb-multiarch}
ESHINE_SYSROOT=${ESHINE_SYSROOT:-/usr/aarch64-linux-gnu/include}
ESHINE_CONTAINER_ENGINE=${ESHINE_CONTAINER_ENGINE:-docker}

export REPO ESHINE_WORK ESHINE_LINUX_DIR ESHINE_MUSL_DIR ESHINE_CJSON_DIR \
       ESHINE_ZLIB_DIR ESHINE_BUSYBOX_DIR ESHINE_POKY_DIR ESHINE_YOCTO_BUILD \
       ESHINE_RUN_DIR ESHINE_LOG_DIR ESHINE_TMP_DIR ESHINE_DOWNLOAD_DIR \
       ESHINE_LINUX_IMAGE ESHINE_INITRAMFS ESHINE_BUSYBOX CROSS ESHINE_QEMU \
       ESHINE_GDB ESHINE_SYSROOT ESHINE_CONTAINER_ENGINE

mkdir -p "$ESHINE_WORK" "$ESHINE_LINUX_DIR" "$ESHINE_MUSL_DIR" \
         "$ESHINE_CJSON_DIR" "$ESHINE_ZLIB_DIR" "$ESHINE_BUSYBOX_DIR" \
         "$ESHINE_RUN_DIR" "$ESHINE_LOG_DIR" "$ESHINE_TMP_DIR" \
         "$ESHINE_DOWNLOAD_DIR" 2>/dev/null || true